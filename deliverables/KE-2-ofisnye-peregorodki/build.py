def img_html(img):
    return (f'  <figure>\n'
            f'    <img src="/wp-content/uploads/{img["file"]}"\n'
            f'         alt="{esc(img["alt"])}"\n'
            f'         width="1200" height="800" loading="lazy">\n'
            f'  </figure>')


def render_html():
    by_heading = {i["after"]: i for i in IMAGES if i["after"]}
    out = ["<!-- ================================================================= -->",
           "<!-- КЕ-2. Содержательный блок страницы офисных перегородок            -->",
           f"<!-- URL: {PAGE.replace(BASE, 'genglass.ru')} -->",
           "<!-- H1 стоит на странице отдельно, здесь не дублируется.              -->",
           "<!-- ================================================================= -->",
           "",
           '<section class="seo-block seo-ofisnye-peregorodki">']
    first_img_done = False
    for block in BLOCKS:
        kind = block[0]
        if kind == "p":
            out.append(f"  <p>{to_html(block[1])}</p>")
            if not first_img_done and len([b for b in BLOCKS[:BLOCKS.index(block) + 1]
                                           if b[0] == "p"]) == 2:
                out.append(img_html(IMAGES[0]))
                first_img_done = True
        elif kind == "h2":
            out.append(f"  <h2>{esc(block[1])}</h2>")
            img = by_heading.get(block[1])
            if img:
                out.append(img_html(img))
        elif kind == "h3":
            out.append(f"  <h3>{esc(block[1])}</h3>")
        elif kind == "ul":
            out.append("  <ul>")
            out.extend(f"    <li>{to_html(i)}</li>" for i in block[1])
            out.append("  </ul>")
        elif kind == "table":
            out.append('  <table class="stages">')
            out.append("    <thead><tr>"
                       + "".join(f"<th>{esc(h)}</th>" for h in block[1])
                       + "</tr></thead>")
            out.append("    <tbody>")
            for row in block[2]:
                out.append("      <tr>"
                           + "".join(f"<td>{esc(c)}</td>" for c in row)
                           + "</tr>")
            out.append("    </tbody>")
            out.append("  </table>")
        elif kind == "faq":
            for q, a in block[1]:
                out.append(f"  <h3>{esc(q)}</h3>")
                out.append(f"  <p>{esc(a)}</p>")
    out.append("</section>")
    out.append("")
    out.append("<!-- ================================================================= -->")
    out.append("<!-- SCHEMA.ORG: Service + FAQPage + BreadcrumbList                    -->")
    out.append("<!-- Тексты ответов совпадают с видимыми на странице посимвольно.      -->")
    out.append("<!-- ================================================================= -->")
    for schema in (breadcrumb_schema(), service_schema(), faq_schema()):
        out.append("")
        out.append('<script type="application/ld+json">')
        out.append(json.dumps(schema, ensure_ascii=False, indent=2))
        out.append("</script>")
    return "\n".join(out) + "\n"


def render_md():
    out = [f"# {H1}", "",
           f"**Title:** {TITLE}  ", f"**Description:** {DESCRIPTION}", "", "---", ""]
    for block in BLOCKS:
        kind = block[0]
        if kind == "h2":
            out += [f"## {block[1]}", ""]
        elif kind == "h3":
            out += [f"### {block[1]}", ""]
        elif kind == "p":
            out += [block[1], ""]
        elif kind == "ul":
            out += [f"- {i}" for i in block[1]] + [""]
        elif kind == "table":
            out.append("| " + " | ".join(block[1]) + " |")
            out.append("|" + "|".join(["---"] * len(block[1])) + "|")
            for row in block[2]:
                out.append("| " + " | ".join(row) + " |")
            out.append("")
        elif kind == "faq":
            for q, a in block[1]:
                out += [f"**{q}?**", "", a, ""]
    return "\n".join(out)


def render_docx(path):
    from docx import Document
    from docx.shared import Pt

    doc = Document()
    doc.core_properties.title = TITLE
    doc.add_heading(H1, level=1)

    meta = doc.add_paragraph()
    meta.add_run("Title: ").bold = True
    meta.add_run(TITLE + "\n")
    meta.add_run("Description: ").bold = True
    meta.add_run(DESCRIPTION)
    for r in meta.runs:
        r.font.size = Pt(9)

    for block in BLOCKS:
        kind = block[0]
        if kind == "h2":
            doc.add_heading(block[1], level=2)
        elif kind == "h3":
            doc.add_heading(block[1], level=3)
        elif kind == "p":
            doc.add_paragraph(plain(block[1]))
        elif kind == "ul":
            for i in block[1]:
                doc.add_paragraph(plain(i), style="List Bullet")
        elif kind == "table":
            head, rows = block[1], block[2]
            t = doc.add_table(rows=1, cols=len(head))
            t.style = "Table Grid"
            for cell, text in zip(t.rows[0].cells, head):
                cell.text = text
                for p in cell.paragraphs:
                    for r in p.runs:
                        r.bold = True
            for row in rows:
                for cell, text in zip(t.add_row().cells, row):
                    cell.text = text
            doc.add_paragraph()
        elif kind == "faq":
            for q, a in block[1]:
                p = doc.add_paragraph()
                p.add_run(q + "?").bold = True
                doc.add_paragraph(a)

    doc.add_page_break()
    doc.add_heading("Ссылки в тексте", level=2)
    for anchor, url in LINKS.items():
        doc.add_paragraph(f"{anchor} - {url}", style="List Bullet")

    doc.add_heading("Изображения", level=2)
    for i, img in enumerate(IMAGES, 1):
        place = f"после H2 «{img['after']}»" if img["after"] else "после лида"
        doc.add_paragraph(f"{i}. {img['file']} (WebP, до 300 КБ). "
                          f"alt: {img['alt']}. Ставится {place}.",
                          style="List Bullet")
    doc.save(path)


