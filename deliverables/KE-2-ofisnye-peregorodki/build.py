def selfcheck():
    parts = visible_parts()
    text = " ".join(parts)
    volume = sum(len(p) for p in parts)
    problems, notes = [], []

    notes.append(f"объём: {volume} знаков с пробелами")
    if not 10000 <= volume <= 12000:
        problems.append(f"объём {volume}, норма 10000-12000")

    h2 = [b[1] for b in BLOCKS if b[0] == "h2"]
    if h2 != EXPECTED_H2:
        problems.append("H2 разошлись с карточкой")

    h3 = [b[1] for b in BLOCKS if b[0] == "h3"]
    notes.append(f"H3 вне FAQ: {len(h3)} ({', '.join(h3)})")
    if "Что входит в наши 20-25 рабочих дней" not in h3:
        problems.append("нет H3 «Что входит в наши 20-25 рабочих дней»")
    if len([x for x in h3 if x not in ("Что входит в наши 20-25 рабочих дней",)]) != 3:
        problems.append("схем зонирования не три")

    fq = [q for q, _ in faq_pairs()]
    if len(fq) != 8:
        problems.append(f"FAQ {len(fq)} пар, нужно 8")
    for q in REQUIRED_FAQ:
        if q not in fq:
            problems.append(f"нет обязательного вопроса: {q}")

    digits = re.findall(r"\d[\d\s.,]*", text)
    notes.append(f"числовых значений: {len(digits)}")
    if len(digits) < 15:
        problems.append(f"цифр {len(digits)}, нужно минимум 15")

    # дБ не изобретаем
    if re.search(r"\d\s*дб", text, re.I):
        problems.append("в тексте появилось значение в дБ")

    # цена за м2
    if re.search(r"(от|за)\s*\d[\d\s]*\s*(₽|руб)[^.]{0,20}(м2|м²|квадратн)", text, re.I):
        problems.append("похоже на цену за квадратный метр")

    for dash in ("—", "–"):
        if dash in text:
            problems.append(f"найдено тире {dash!r}")
    for word in ("преимуществ", "единственн", "лучший", "лучшая", "лучшие"):
        if word in text.lower():
            problems.append(f"стоп-слово: {word}")
    if "Metal-GM" in text or "metal-gm" in text.lower():
        problems.append("упомянут Metal-GM")

    md = render_md()
    urls = set(LINK_RE.findall(md))
    for anchor, url in urls:
        if LINKS.get(anchor) != url:
            problems.append(f"недопустимая ссылка: [{anchor}]({url})")
    if len(urls) != 4:
        problems.append(f"ссылок {len(urls)}, нужно 4")
    for s in STOP_URLS:
        if s in md:
            problems.append(f"ссылка из стоп-листа: {s}")

    brand = len(re.findall(r"GENGLASS", text))
    notes.append(f"GENGLASS: {brand} раз, 1 на {volume // max(brand, 1)} знаков")
    if re.search(r"Genglass|GenGlass", text):
        problems.append("бренд не заглавными")
    if brand and volume // brand > 1500:
        problems.append(f"бренд 1 на {volume // brand} знаков, норма 1 на 1500")

    # Schema
    schemas = [breadcrumb_schema(), service_schema(), faq_schema()]
    types = [s["@type"] for s in schemas]
    if set(types) != {"Service", "FAQPage", "BreadcrumbList"}:
        problems.append(f"Schema: {types}")

    if len(IMAGES) != 4:
        problems.append(f"изображений {len(IMAGES)}, в карточке 4 промпта")
    if any(not i["alt"].strip() for i in IMAGES):
        problems.append("пустой alt у изображения")

    if "12 месяцев" not in text:
        problems.append("не названа гарантия 12 месяцев")
    if "по договору" not in text.lower() and "договором" not in text.lower():
        problems.append("не оговорена гарантия для объектов по договору")

    return volume, notes, problems


