LINK_RE = re.compile(r"\[([^\]]+)\]\(([^)]+)\)")


def plain(text):
    return LINK_RE.sub(r"\1", text)


def esc(text):
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def to_html(text):
    return LINK_RE.sub(r'<a href="\2">\1</a>', esc(text))


def faq_pairs():
    for block in BLOCKS:
        if block[0] == "faq":
            return block[1]
    return []


def visible_parts():
    parts = []
    for block in BLOCKS:
        kind = block[0]
        if kind in ("h2", "h3", "p"):
            parts.append(plain(block[1]))
        elif kind == "ul":
            parts.extend(plain(i) for i in block[1])
        elif kind == "table":
            parts.extend(block[1])
            for row in block[2]:
                parts.extend(c for c in row if c)
        elif kind == "faq":
            for q, a in block[1]:
                parts.append(q)
                parts.append(a)
    return parts


