def build(path):
    doc = Document()
    doc.add_heading(TITLE, level=1)

    p = doc.add_paragraph(LEAD)
    p.runs[0].bold = True

    for head, body, fix in ITEMS:
        doc.add_heading(head, level=2)
        doc.add_paragraph(body)
        doc.add_paragraph(fix)

    doc.add_heading("Итог", level=2)
    for para in OUTRO:
        doc.add_paragraph(para)

    doc.add_page_break()
    doc.add_heading("Служебное: варианты заголовка для А/Б", level=2)
    for t in ALT_TITLES:
        doc.add_paragraph(t, style="List Number")

    doc.add_heading("Обложка", level=2)
    doc.add_paragraph(
        "Светлая гостиная, наполовину «до» и наполовину «после»: слева глухая "
        "стена и одна люстра, справа стеклянная перегородка и свет. Формат 3:2, "
        "без текста в кадре.")

    note = doc.add_paragraph(
        "Объём: около 3 200 знаков. Формат Дзена: короткие абзацы, подзаголовки, "
        "вопрос в финале под комментарии.")
    note.runs[0].font.size = Pt(9)

    doc.save(path)


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, "GENGLASS_dzen_krasnye_flagi.docx")
    build(out)

    text = "\n".join(
        [TITLE, LEAD]
        + [x for item in ITEMS for x in item]
        + OUTRO
    )
    assert "—" not in text and "–" not in text, "найдено длинное тире"
    print(f"Готово: {out}")
    print(f"Объём тела статьи: {len(text)} знаков с пробелами")
