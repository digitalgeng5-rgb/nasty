def build(art, path):
    doc = Document()
    doc.add_heading(art["title"], level=1)

    lead = doc.add_paragraph(art["lead"])
    lead.runs[0].bold = True

    for head, paras in art["blocks"]:
        doc.add_heading(head, level=2)
        for p in paras:
            doc.add_paragraph(p)

    doc.add_heading("Коротко", level=2)
    for p in art["outro"]:
        doc.add_paragraph(p)

    doc.add_page_break()
    doc.add_heading("Служебное: варианты заголовка для А/Б", level=2)
    for t in art["alt_titles"]:
        doc.add_paragraph(t, style="List Number")

    doc.add_heading("Обложка", level=2)
    doc.add_paragraph(art["cover"])

    note = doc.add_paragraph(
        art["note"] + " Тон: сдержанно-экспертный, без шуток и восклицаний, "
        "живость держится на конкретике.")
    note.runs[0].font.size = Pt(9)

    doc.save(path)


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    for art in ARTICLES:
        text = "\n".join(
            [art["title"], art["lead"]]
            + [p for _, paras in art["blocks"] for p in paras]
            + art["outro"]
        )
        for bad in ("—", "–"):
            assert bad not in text, f"{art['file']}: найдено длинное тире"
        # Ловим рекламные превосходные обороты, а не сравнительное «лучше».
        for word in ("единственн", "лучший", "лучшая", "лучшие", "лучшее"):
            assert word not in text.lower(), f"{art['file']}: стоп-слово {word}"
        assert "!" not in text, f"{art['file']}: восклицательный знак"

        path = os.path.join(here, art["file"])
        build(art, path)
        print(f"{art['file']}: {len(text)} знаков с пробелами")
