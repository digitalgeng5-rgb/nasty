def body_text():
    """Видимый текст статьи без служебного блока и подписей к фото."""
    parts = [TITLE, LEAD]
    for head, paras, _ in BLOCKS:
        parts.append(head)
        parts.extend(paras)
    parts.extend(OUTRO)
    return "\n".join(parts)


def photo(slot):
    for item in PHOTOS:
        if item[0] == slot:
            return item
    return None


def build_docx(path):
    doc = Document()
    doc.add_heading(TITLE, level=1)

    lead = doc.add_paragraph(LEAD)
    lead.runs[0].bold = True

    def marker(slot):
        item = photo(slot)
        if not item:
            return
        par = doc.add_paragraph("[ФОТО: %s]" % item[3])
        par.runs[0].italic = True
        par.runs[0].font.size = Pt(9)

    marker("cover")

    for head, paras, slot in BLOCKS:
        doc.add_heading(head, level=2)
        for text in paras:
            doc.add_paragraph(text)
            if slot == "plan-2" and text.startswith("Сделали иначе"):
                marker("stekla")
            if slot == "plan-3" and text.startswith("Что стоит знать"):
                marker("uzel")
        if slot:
            marker(slot)

    doc.add_heading("Итог", level=2)
    for text in OUTRO:
        doc.add_paragraph(text)

    doc.add_page_break()

    doc.add_heading("Служебное: варианты заголовка для А/Б", level=2)
    for title in ALT_TITLES:
        doc.add_paragraph(title, style="List Number")

    doc.add_heading("Служебное: какие нужны фотографии", level=2)
    doc.add_paragraph(
        "Семь кадров: пять обязательных и два желательных. Съёмка дневная, "
        "без вспышки в лоб. Ни в одном кадре нет текста, логотипов и людей."
    )
    for i, (slot, ratio, min_w, caption, place, brief, status) in enumerate(PHOTOS, 1):
        head = doc.add_paragraph()
        run = head.add_run("%d. %s (%s, от %d px, %s)" % (i, place, ratio, min_w, status))
        run.bold = True
        doc.add_paragraph(brief)
        cap = doc.add_paragraph("Подпись под фото: %s" % caption)
        cap.runs[0].italic = True

    doc.add_heading("Служебное: заметки", level=2)
    for note in SERVICE_NOTES:
        doc.add_paragraph(note, style="List Bullet")

    tail = doc.add_paragraph("Объём тела статьи: %d знаков с пробелами." % len(body_text()))
    tail.runs[0].font.size = Pt(9)

    doc.save(path)


def figure_html(slot):
    item = photo(slot)
    if not item:
        return ""
    return (
        '    <figure class="ph" data-slot="%s" data-ratio="%s" data-min-w="%d">\n'
        '      <figcaption>%s</figcaption>\n'
        '    </figure>\n' % (item[0], item[1], item[2], html.escape(item[3]))
    )


