def body_text():
    """Весь видимый текст статьи без служебного блока и подписей к фото."""
    parts = [TITLE, LEAD]
    for head, paras in INTRO + PLANS + [LIMITS, MONEY]:
        parts.append(head)
        parts.extend(paras)
    parts.extend([" ".join(TABLE_HEAD)] + [" ".join(r) for r in TABLE_ROWS])
    parts.extend(OUTRO)
    return "\n".join(parts)


def build_docx(path):
    doc = Document()
    doc.add_heading(TITLE, level=1)

    p = doc.add_paragraph(LEAD)
    p.runs[0].bold = True

    def photo_marker(slot):
        for ph in PHOTOS:
            if ph[0] == slot:
                mark = doc.add_paragraph("[ФОТО: %s]" % ph[3])
                mark.runs[0].italic = True
                mark.runs[0].font.size = Pt(9)

    photo_marker("cover")

    for head, paras in INTRO:
        doc.add_heading(head, level=2)
        for text in paras:
            doc.add_paragraph(text)

    for i, (head, paras) in enumerate(PLANS, start=1):
        doc.add_heading(head, level=2)
        for text in paras:
            doc.add_paragraph(text)
        photo_marker("plan-%d" % i)
        if i in EXTRA_AFTER:
            photo_marker(EXTRA_AFTER[i])

    doc.add_heading("Что подходит под какую планировку", level=2)
    photo_marker("shema")
    table = doc.add_table(rows=1, cols=len(TABLE_HEAD))
    table.style = "Table Grid"
    for cell, name in zip(table.rows[0].cells, TABLE_HEAD):
        cell.text = name
        cell.paragraphs[0].runs[0].bold = True
    for row in TABLE_ROWS:
        cells = table.add_row().cells
        for cell, value in zip(cells, row):
            cell.text = value

    for head, paras in [LIMITS, MONEY]:
        doc.add_heading(head, level=2)
        for text in paras:
            doc.add_paragraph(text)

    doc.add_heading("Итог", level=2)
    for text in OUTRO:
        doc.add_paragraph(text)

    doc.add_page_break()

    doc.add_heading("Служебное: варианты заголовка для А/Б", level=2)
    for title in ALT_TITLES:
        doc.add_paragraph(title, style="List Number")

    doc.add_heading("Служебное: техзадание на фотографии", level=2)
    doc.add_paragraph(
        "Восемь кадров: пять обязательных и три желательных. Съёмка дневная, "
        "без вспышки в лоб. Ни в одном кадре нет текста, логотипов и людей."
    )
    ph_table = doc.add_table(rows=1, cols=5)
    ph_table.style = "Table Grid"
    heads = ["#", "Кадр и место в статье", "Формат", "Что должно быть в кадре", "Статус"]
    for cell, name in zip(ph_table.rows[0].cells, heads):
        cell.text = name
        cell.paragraphs[0].runs[0].bold = True
    for i, (slot, ratio, min_w, caption, place, brief, status) in enumerate(PHOTOS, start=1):
        cells = ph_table.add_row().cells
        cells[0].text = str(i)
        cells[1].text = "%s\n%s" % (caption, place)
        cells[2].text = "%s, от %d px" % (ratio, min_w)
        cells[3].text = brief
        cells[4].text = status

    doc.add_heading("Служебное: заметки", level=2)
    for note in SERVICE_NOTES:
        doc.add_paragraph(note, style="List Bullet")

    tail = doc.add_paragraph(
        "Объём тела статьи: %d знаков с пробелами." % len(body_text())
    )
    tail.runs[0].font.size = Pt(9)
    tail.alignment = WD_ALIGN_PARAGRAPH.LEFT

    doc.save(path)


def figure_html(slot):
    for s, ratio, min_w, caption, place, brief, status in PHOTOS:
        if s == slot:
            return (
                '    <figure class="ph" data-slot="%s" data-ratio="%s" data-min-w="%d">\n'
                '      <figcaption>%s</figcaption>\n'
                '    </figure>\n' % (s, ratio, min_w, html.escape(caption))
            )
    return ""


