def body_text():
    """Весь текст статьи: заголовок, лид, блоки, итог."""
    parts = [TITLE, LEAD]
    for head, paras, _ in BLOCKS:
        parts.append(head)
        parts.extend(paras)
    parts.extend(OUTRO)
    return "\n".join(parts)


def inline_slot(block_slot, text):
    for slot, prefix, photo_slot in INLINE_PHOTOS:
        if slot == block_slot and text.startswith(prefix):
            return photo_slot
    return None


def build_docx(path):
    doc = Document()
    doc.add_heading(TITLE, level=1)

    lead = doc.add_paragraph(LEAD)
    lead.runs[0].bold = True

    for head, paras, _ in BLOCKS:
        doc.add_heading(head, level=2)
        for text in paras:
            doc.add_paragraph(text)

    doc.add_heading("Итог", level=2)
    for text in OUTRO:
        doc.add_paragraph(text)

    doc.save(path)


def figure_html(slot):
    for s, ratio, min_w, caption in PHOTOS:
        if s == slot:
            return (
                '    <figure class="ph" data-slot="%s" data-ratio="%s" data-min-w="%d">\n'
                '      <figcaption>%s</figcaption>\n'
                '    </figure>\n' % (s, ratio, min_w, html.escape(caption))
            )
    return ""


def build_html(path):
    out = []
    add = out.append
    add('<!doctype html>\n<html lang="ru">\n<head>\n<meta charset="utf-8">\n')
    add('<meta name="viewport" content="width=device-width, initial-scale=1">\n')
    add('<title>%s</title>\n' % html.escape(TITLE))
    add('<link rel="stylesheet" href="../assets/zen.css">\n</head>\n<body>\n\n')
    add('<div class="topbar">\n  <div class="inner">\n')
    add('    <a href="../index.html">&larr; Все статьи</a>\n')
    add('    <span class="spacer"></span>\n')
    add('    <span class="stat" data-count></span>\n  </div>\n</div>\n\n')
    add('<div class="page">\n  <article class="article">\n\n')
    add('    <h1>%s</h1>\n\n' % html.escape(TITLE))
    add(figure_html("cover"))
    add('\n    <p class="lead">%s</p>\n\n' % html.escape(LEAD))

    for head, paras, slot in BLOCKS:
        add('    <h2>%s</h2>\n' % html.escape(head))
        for text in paras:
            add('    <p>%s</p>\n' % html.escape(text))
            extra = inline_slot(slot, text)
            if extra:
                add(figure_html(extra))
        if slot:
            add(figure_html(slot))
        add('\n')

    add('    <h2>Итог</h2>\n')
    for text in OUTRO:
        add('    <p>%s</p>\n' % html.escape(text))

    add('\n  </article>\n</div>\n\n')
    add('<script src="../assets/photo-fit.js"></script>\n</body>\n</html>\n')

    with open(path, "w", encoding="utf-8") as f:
        f.write("".join(out))


def selfcheck():
    problems = []
    text = body_text()

    for dash in ("—", "–"):
        if dash in text:
            problems.append("найдено длинное тире")
    for pattern in (r"преимущ", r"лучш(ий|ая|ее|ие|его|ему|им|их|ими)",
                    r"единственн", r"уникальн", r"конкурент"):
        if re.search(pattern, text, re.IGNORECASE):
            problems.append("стоп-слово: %s" % pattern)
    if not (3500 <= len(text) <= 4500):
        problems.append("объём вне диапазона 3500-4500: %d" % len(text))
    if text.count("GENGLASS") < 1:
        problems.append("бренд не упомянут")
    if len(re.findall(r"genglass", text, re.IGNORECASE)) != text.count("GENGLASS"):
        problems.append("бренд написан не заглавными")

    longest = max(len(p) for _, paras, _ in BLOCKS for p in paras)
    if longest > 420:
        problems.append("абзац длиннее 420 знаков: %d" % longest)

    slots = [p[0] for p in PHOTOS]
    if len(slots) != len(set(slots)):
        problems.append("повторяются id слотов под фото")
    return problems


